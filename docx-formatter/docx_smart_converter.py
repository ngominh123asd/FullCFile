def set_font(run, bold=False, italic=False, size=13):
    run.font.name = 'Times New Roman'
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic

def process_inline_formatting(paragraph, text, base_size=13, is_bold=False):
    # Matches:
    # 1. `code` (inline code snippets in Courier New font)
    # 2. **bold** or __bold__
    # 3. *italic* or _italic_ (with word boundaries \b to avoid intra-word underscores like GEMINI_API_KEY)
    tokens = re.split(r'(`[^`]+`|\*\*.*?\*\*|__.*?__|(?<!\*)\*[^\*]+\*(?!\*)|(?<!_)\b_[^_]+_\b(?!_))', text)
    
    for token in tokens:
        if not token:
            continue
        
        bold = is_bold
        italic = False
        font_name = 'Times New Roman'
        content = token
        
        if token.startswith('`') and token.endswith('`'):
            font_name = 'Courier New'
            content = token[1:-1]
        elif token.startswith('**') and token.endswith('**'):
            bold = True
            content = token[2:-2]
        elif token.startswith('__') and token.endswith('__'):
            bold = True
            content = token[2:-2]
        elif token.startswith('*') and token.endswith('*'):
            italic = True
            content = token[1:-1]
        elif token.startswith('_') and token.endswith('_'):
            italic = True
            content = token[1:-1]
            
        run = paragraph.add_run(content)
        run.font.name = font_name
        run.font.size = Pt(base_size)
        run.font.bold = bold
        run.font.italic = italic

def add_paragraph_left_border(p, color_hex="4285F4", size_eight=24):
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    pPr = p._p.get_or_add_pPr()
    pBdr = OxmlElement('w:pBdr')
    left = OxmlElement('w:left')
    left.set(qn('w:val'), 'single')
    left.set(qn('w:sz'), str(size_eight)) # 24 eighths of a pt = 3pt
    left.set(qn('w:space'), '12')
    left.set(qn('w:color'), color_hex)
    pBdr.append(left)
    pPr.append(pBdr)

def set_paragraph_shading(p, color_hex="F0F4FE"):
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    pPr = p._p.get_or_add_pPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), color_hex)
    pPr.append(shd)

def convert_md_to_docx(input_md, output_docx):
    doc = Document()
    
    # Configure core document properties to show up beautifully in Windows Explorer tooltip & Details tab
    core_properties = doc.core_properties
    core_properties.author = 'Masuzu'
    core_properties.last_modified_by = 'Masuzu'
    core_properties.comments = 'generated by Masuzu'
    core_properties.subject = 'generated by Masuzu'
    core_properties.title = 'generated by Masuzu'
    core_properties.category = 'generated by Masuzu'
    core_properties.keywords = 'Masuzu'  # This maps to "Tags / Nhãn" in Windows Explorer
    
    style = doc.styles['Normal']
    font = style.font
    font.name = 'Times New Roman'
    font.size = Pt(13)
    
    with open(input_md, 'r', encoding='utf-8') as f:
        lines = f.readlines()
        
    i = 0
    num_lines = len(lines)
    
    while i < num_lines:
        line = lines[i].strip('\n')
        stripped_line = line.strip()
        
        # 1. Skip completely empty lines
        if not stripped_line:
            i += 1
            continue
            
        # 2. Check for Code Block
        if stripped_line.startswith('```'):
            i += 1
            code_lines = []
            while i < num_lines and not lines[i].strip().startswith('```'):
                code_lines.append(lines[i].strip('\n'))
                i += 1
            i += 1  # skip ending ```
            
            for c_line in code_lines:
                p = doc.add_paragraph()
                run = p.add_run(c_line)
                run.font.name = 'Courier New'
                run.font.size = Pt(11)
            continue
            
        # 3. Check for horizontal line separators
        if stripped_line == '---' or stripped_line == '***' or stripped_line == '___':
            doc.add_paragraph().add_run().add_break()
            p = doc.add_paragraph("----------------------------------------------------------------------")
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            doc.add_paragraph()
            i += 1
            continue
            
        # 4. Check for Blockquotes / Callout blocks
        if stripped_line.startswith('>'):
            blockquote_lines = []
            while i < num_lines and lines[i].strip().startswith('>'):
                blockquote_lines.append(lines[i].strip('\n').strip())
                i += 1
                
            callout_type = 'QUOTE'
            first_line_clean = blockquote_lines[0][1:].strip()
            
            callout_match = re.match(r'^\[!(NOTE|IMPORTANT|WARNING|TIP|CAUTION)\]', first_line_clean)
            start_idx = 0
            if callout_match:
                callout_type = callout_match.group(1)
                start_idx = 1
                
            if callout_type == 'NOTE':
                border_color = "4285F4"  # Google Blue
                bg_color = "F0F4FE"
                prefix = "Lưu ý: "
            elif callout_type in ['IMPORTANT', 'WARNING', 'CAUTION']:
                border_color = "EA4335"  # Google Red
                bg_color = "FCE8E6"
                prefix = "Quan trọng: "
            elif callout_type == 'TIP':
                border_color = "34A853"  # Google Green
                bg_color = "E6F4EA"
                prefix = "Mẹo: "
            else:
                border_color = "9AA0A6"  # Gray
                bg_color = "F8F9FA"
                prefix = ""
                
            clean_lines = []
            for b_line in blockquote_lines[start_idx:]:
                clean_line = b_line[1:].strip()
                if clean_line:
                    clean_lines.append(clean_line)
                    
            if clean_lines:
                p = doc.add_paragraph()
                p.paragraph_format.line_spacing = 1.15
                p.paragraph_format.left_indent = Pt(24)
                
                # Apply borders and shading for high premium layout
                add_paragraph_left_border(p, border_color)
                set_paragraph_shading(p, bg_color)
                
                if prefix:
                    prefix_run = p.add_run(prefix)
                    set_font(prefix_run, bold=True, size=12)
                    
                combined_text = " ".join(clean_lines)
                process_inline_formatting(p, combined_text, base_size=12, is_bold=False)
                
                # Make text italic for an elegant quotes feel
                for run in p.runs:
                    if run.text != prefix:
                        run.font.italic = True
                        
                doc.add_paragraph()
            continue
            
        # 5. Check for GFM standard tables
        if stripped_line.startswith('|') and stripped_line.endswith('|'):
            table_lines = []
            while i < num_lines and lines[i].strip().startswith('|') and lines[i].strip().endswith('|'):
                table_lines.append(lines[i].strip('\n').strip())
                i += 1
                
            if len(table_lines) > 0:
                rows_data = []
                for t_line in table_lines:
                    # check if separator row
                    clean_t_line = t_line.replace(':', '').replace('-', '').replace(' ', '').replace('|', '')
                    if clean_t_line == '':
                        continue
                    cells = [c.strip() for c in t_line.split('|')[1:-1]]
                    rows_data.append(cells)
                    
                if rows_data:
                    num_rows = len(rows_data)
                    num_cols = max(len(r) for r in rows_data)
                    
                    # Create beautifully grid-bordered Word table!
                    table = doc.add_table(rows=num_rows, cols=num_cols, style='Table Grid')
                    
                    for r_idx, row_cells in enumerate(rows_data):
                        for c_idx, cell_text in enumerate(row_cells):
                            if c_idx < num_cols:
                                word_cell = table.cell(r_idx, c_idx)
                                word_cell.text = ""
                                p = word_cell.paragraphs[0]
                                p.paragraph_format.line_spacing = 1.15
                                p.paragraph_format.space_before = Pt(4)
                                p.paragraph_format.space_after = Pt(6)
                                is_header = (r_idx == 0)
                                process_inline_formatting(p, cell_text, base_size=11, is_bold=is_header)
                                
                    doc.add_paragraph()
            continue
            
        # 6. Check for Header / Heading
        header_match = re.match(r'^(#{1,6})\s+(.*)', stripped_line)
        if header_match:
            level = len(header_match.group(1))
            text = header_match.group(2)

            p = doc.add_paragraph()
            p.paragraph_format.line_spacing = 1.5
            p.paragraph_format.space_before = Pt(12)
            p.paragraph_format.space_after = Pt(6)

            # Thò thụt các cấp tiêu đề
            if level > 2:
                p.paragraph_format.left_indent = Pt(24 * (level - 2))

            size = 18 if level == 1 else (16 if level == 2 else (14 if level == 3 else 13))

            process_inline_formatting(p, text, base_size=size, is_bold=True)
            i += 1
            continue
            
        # 7. Check for bulleted/numbered lists
        list_match = re.match(r'^(\s*)([-*+]|\d+\.)\s+(.*)', line)
        if list_match:
            indentation = list_match.group(1)
            bullet = list_match.group(2)
            content = list_match.group(3)
            
            p = doc.add_paragraph()
            p.paragraph_format.line_spacing = 1.5
            
            level = len(indentation) // 2
            p.paragraph_format.left_indent = Pt(18 * (level + 1))
            
            bullet_run = p.add_run(f"{bullet} ")
            set_font(bullet_run)
            
            process_inline_formatting(p, content)
            i += 1
            continue
            
        # 8. Regular text paragraph
        p = doc.add_paragraph()
        p.paragraph_format.line_spacing = 1.5
        process_inline_formatting(p, line)
        i += 1
        
    doc.save(output_docx)
    print(f"Successfully converted MD '{input_md}' ➔ DOCX '{output_docx}'")

def resolve_tab_stops(text, tab_stops=[16, 24] + list(range(28, 200, 4))):
    parts = text.split('\t')
    if len(parts) == 1:
        return text
        
    result = parts[0]
    current_pos = len(parts[0])
    
    for part in parts[1:]:
        # Find the next tab stop that is strictly greater than current_pos
        next_stop = 4 + (current_pos // 4) * 4 # Default fallback to 4-space grid
        for stop in tab_stops:
            if stop > current_pos:
                next_stop = stop
                break
                
        # Pad with non-breaking spaces to reach next_stop
        pad_len = next_stop - current_pos
        result += '\u00a0' * pad_len
        result += part
        current_pos = next_stop + len(part)
        
    return result

def get_paragraph_markdown(p):
    runs = []
    for child in p._p.iterchildren():
        if child.tag.endswith('r'):
            from docx.text.run import Run
            runs.append(Run(child, p))
        elif child.tag.endswith('hyperlink'):
            for sub_child in child.iterchildren():
                if sub_child.tag.endswith('r'):
                    from docx.text.run import Run
                    runs.append(Run(sub_child, p))
                    
    if not runs:
        return resolve_tab_stops(p.text) if p.text else ""
        
    merged_runs = []
    current_text = ""
    current_bold = None
    current_italic = None
    current_code = None
    
    for r in runs:
        text = r.text
        if not text:
            continue
            
        bold = bool(r.bold or (r.font and r.font.bold) or (r.style and 'bold' in r.style.name.lower()))
        italic = bool(r.italic or (r.font and r.font.italic) or (r.style and 'italic' in r.style.name.lower()))
        code = bool(r.font and r.font.name and 'courier' in r.font.name.lower())
        
        # If it's the first run, or formatting matches the current run, merge it
        if current_bold is None:
            current_text = text
            current_bold = bold
            current_italic = italic
            current_code = code
        elif current_bold == bold and current_italic == italic and current_code == code:
            current_text += text
        else:
            # Save the previous run
            merged_runs.append((current_text, current_bold, current_italic, current_code))
            # Start new run
            current_text = text
            current_bold = bold
            current_italic = italic
            current_code = code
            
    if current_bold is not None:
        merged_runs.append((current_text, current_bold, current_italic, current_code))
        
    # Format each merged run as Markdown
    md_text = ""
    for text, bold, italic, code in merged_runs:
        if not text:
            continue
            
        stripped = text.strip()
        if not stripped:
            md_text += text
            continue
            
        leading = text[:len(text) - len(text.lstrip())]
        trailing = text[len(text.rstrip()):]
        
        # Do not format pure punctuation/non-alphanumeric runs as bold or italic
        is_pure_punctuation = not any(c.isalnum() for c in stripped)
        
        if code:
            formatted = f"`{stripped}`"
        elif bold and italic and not is_pure_punctuation:
            formatted = f"***{stripped}***"
        elif bold and not is_pure_punctuation:
            formatted = f"**{stripped}**"
        elif italic and not is_pure_punctuation:
            formatted = f"*{stripped}*"
        else:
            formatted = stripped
            
        md_text += leading + formatted + trailing
        
    return resolve_tab_stops(md_text)

def iter_block_items(parent):
    from docx.document import Document as _Document
    if isinstance(parent, _Document):
        parent_elm = parent.element.body
    else:
        parent_elm = parent._element
        
    for child in parent_elm.iterchildren():
        if child.tag.endswith('p'):
            yield Paragraph(child, parent)
        elif child.tag.endswith('tbl'):
            yield Table(child, parent)

def has_table_borders(table):
    try:
        tblPr = table._tbl.tblPr
        tblBorders = tblPr.find('{http://schemas.openxmlformats.org/wordprocessingml/2006/main}tblBorders')
        if tblBorders is not None:
            for b_type in ['top', 'left', 'bottom', 'right', 'insideH', 'insideV']:
                b = tblBorders.find(f'{{http://schemas.openxmlformats.org/wordprocessingml/2006/main}}{b_type}')
                if b is not None:
                    val = b.get('{http://schemas.openxmlformats.org/wordprocessingml/2006/main}val')
                    if val != 'none' and val != 'nil':
                        return True
            return False
    except Exception:
        pass
    style_name = table.style.name.lower() if (table.style and table.style.name) else ""
    if 'grid' in style_name or 'list' in style_name or 'shading' in style_name:
        return True
    return False

def convert_borderless_table_to_markdown(table):
    md_lines = []
    num_cols = len(table.columns) if table.columns else 0
    if num_cols == 0:
        return ""
        
    # Calculate perfect visual tab stops for the columns
    if num_cols == 2:
        tab_stops = [40]
    elif num_cols == 3:
        tab_stops = [32, 60]
    else:
        tab_stops = [int(80 * col / num_cols) for col in range(1, num_cols)]
        
    for i, row in enumerate(table.rows):
        cell_parts = []
        for cell in row.cells:
            parts = []
            for p in cell.paragraphs:
                p_text = get_paragraph_markdown(p).strip()
                if p_text:
                    parts.append(p_text)
            cell_parts.append(parts)
            
        max_p = max(len(parts) for parts in cell_parts) if cell_parts else 0
        if max_p == 0:
            # 4 spacious lines is standard for signing fields
            md_lines.append("")
            continue
            
        for k in range(max_p):
            row_text_parts = []
            for col_idx, cell in enumerate(cell_parts):
                val = cell[k] if k < len(cell) else ""
                # Indent the very first column of the row by 8 spaces to prevent pushing to the left page edge!
                if col_idx == 0 and val:
                    val = "\u00a0\u00a0\u00a0\u00a0\u00a0\u00a0\u00a0\u00a0" + val
                row_text_parts.append(val)
                
            raw_row = "\t".join(row_text_parts)
            aligned_row = resolve_tab_stops(raw_row, tab_stops=tab_stops)
            md_lines.append(aligned_row)
            
    return "\n".join(md_lines) + "\n"

def convert_table_to_markdown(table):
    if not has_table_borders(table):
        return convert_borderless_table_to_markdown(table)
        
    md_rows = []
    
    # We want to check alignment from the first row to write the GFM separator
    first_row_alignments = []
    if len(table.rows) > 0:
        for cell in table.rows[0].cells:
            align = ":---"
            for p in cell.paragraphs:
                if p.alignment == 1: # Center
                    align = ":---:"
                    break
                elif p.alignment == 2: # Right
                    align = "---:"
                    break
            first_row_alignments.append(align)
            
    for i, row in enumerate(table.rows):
        # Find paragraphs for each cell in this row
        row_cells_paragraphs = []
        for cell in row.cells:
            cell_parts = []
            for p in cell.paragraphs:
                p_text = get_paragraph_markdown(p).strip()
                if p_text:
                    cell_parts.append(p_text)
            row_cells_paragraphs.append(cell_parts)
            
        # Find the maximum number of paragraphs in any cell of this row
        max_p = max(len(parts) for parts in row_cells_paragraphs) if row_cells_paragraphs else 0
        if max_p == 0:
            # Entire row is completely empty (e.g. signature spacer row)
            # Render a single empty Markdown row, or multiple if it is a signature/spacer table
            num_empty_rows = 4 if i > 0 else 1
            for _ in range(num_empty_rows):
                empty_cells = [" " for _ in row.cells]
                md_rows.append(f"| {' | '.join(empty_cells)} |")
                
            if i == 0 and first_row_alignments:
                md_rows.append(f"| {' | '.join(first_row_alignments)} |")
            continue
            
        # Generate max_p sub-rows in Markdown for side-by-side line breaking!
        for k in range(max_p):
            sub_row_cells = []
            for cell_parts in row_cells_paragraphs:
                if k < len(cell_parts):
                    cell_text = cell_parts[k]
                else:
                    cell_text = ""
                # Escape pipe symbols
                cell_text = cell_text.replace("|", "\\|")
                sub_row_cells.append(cell_text)
                
            md_rows.append(f"| {' | '.join(sub_row_cells)} |")
            
            # Insert the GFM separator row after the very first sub-row of the header row
            if i == 0 and k == 0 and first_row_alignments:
                md_rows.append(f"| {' | '.join(first_row_alignments)} |")
                
    return "\n".join(md_rows) + "\n"

def to_roman(n):
    val = [1000, 900, 500, 400, 100, 90, 50, 40, 10, 9, 5, 4, 1]
    syb = ["M", "CM", "D", "CD", "C", "XC", "L", "XL", "X", "IX", "V", "IV", "I"]
    roman = ""
    i = 0
    while n > 0:
        for _ in range(n // val[i]):
            roman += syb[i]
            n -= val[i]
        i += 1
    return roman

def get_level_value(num_fmt, current_num):
    if num_fmt == 'bullet':
        return '-'
    elif num_fmt == 'upperRoman':
        return to_roman(current_num)
    elif num_fmt == 'lowerRoman':
        return to_roman(current_num).lower()
    elif num_fmt == 'upperLetter':
        return chr(ord('A') + current_num - 1) if 1 <= current_num <= 26 else str(current_num)
    elif num_fmt == 'lowerLetter':
        return chr(ord('a') + current_num - 1) if 1 <= current_num <= 26 else str(current_num)
    elif num_fmt == 'decimal':
        return str(current_num)
    return str(current_num)

def get_numbering_info(doc, num_id, ilvl):
    try:
        numbering = doc.part.numbering_part.element
        
        num_elm = None
        for n in numbering.findall('{http://schemas.openxmlformats.org/wordprocessingml/2006/main}num'):
            if n.get('{http://schemas.openxmlformats.org/wordprocessingml/2006/main}numId') == str(num_id):
                num_elm = n
                break
                
        if num_elm is None:
            return 'bullet', '%1.'
            
        abstract_num_id_elm = num_elm.find('{http://schemas.openxmlformats.org/wordprocessingml/2006/main}abstractNumId')
        if abstract_num_id_elm is None:
            return 'bullet', '%1.'
            
        abstract_num_id = abstract_num_id_elm.get('{http://schemas.openxmlformats.org/wordprocessingml/2006/main}val')
        
        abstract_elm = None
        for a in numbering.findall('{http://schemas.openxmlformats.org/wordprocessingml/2006/main}abstractNum'):
            if a.get('{http://schemas.openxmlformats.org/wordprocessingml/2006/main}abstractNumId') == str(abstract_num_id):
                abstract_elm = a
                break
                
        if abstract_elm is None:
            return 'bullet', '%1.'
            
        lvl_elm = None
        for l in abstract_elm.findall('{http://schemas.openxmlformats.org/wordprocessingml/2006/main}lvl'):
            if l.get('{http://schemas.openxmlformats.org/wordprocessingml/2006/main}ilvl') == str(ilvl):
                lvl_elm = l
                break
                
        if lvl_elm is None:
            lvl_elm = abstract_elm.find('{http://schemas.openxmlformats.org/wordprocessingml/2006/main}lvl')
            
        if lvl_elm is not None:
            num_fmt_elm = lvl_elm.find('{http://schemas.openxmlformats.org/wordprocessingml/2006/main}numFmt')
            lvl_text_elm = lvl_elm.find('{http://schemas.openxmlformats.org/wordprocessingml/2006/main}lvlText')
            
            num_fmt = num_fmt_elm.get('{http://schemas.openxmlformats.org/wordprocessingml/2006/main}val') if num_fmt_elm is not None else 'bullet'
            lvl_text = lvl_text_elm.get('{http://schemas.openxmlformats.org/wordprocessingml/2006/main}val') if lvl_text_elm is not None else '%1.'
            
            return num_fmt, lvl_text
    except Exception:
        pass
    return 'bullet', '%1.'

def convert_docx_to_md(input_docx, output_md):
    doc = Document(input_docx)
    md_lines = []
    
    in_code_block = False
    code_lines = []
    
    last_item_type = None  # Tracks block type: 'heading', 'table', 'list', 'paragraph'
    number_trackers = {}
    
    for item in iter_block_items(doc):
        if isinstance(item, Table):
            if in_code_block:
                md_lines.append("```")
                md_lines.extend(code_lines)
                md_lines.append("```")
                md_lines.append("")
                in_code_block = False
                
            # Tables MUST have a blank line before them to prevent merging into preceding paragraphs or lists
            if md_lines and md_lines[-1] != "":
                md_lines.append("")
                
            table_md = convert_table_to_markdown(item)
            md_lines.append(table_md)
            last_item_type = 'table'
            continue
            
        elif isinstance(item, Paragraph):
            p = item
            text = p.text
            style_name = p.style.name.lower() if p.style else ""
            
            pPr = p._element.pPr
            numPr = pPr.numPr if pPr is not None else None
            
            num_fmt = None
            lvl_text = "%1."
            ilvl = 0
            num_id = 0
            
            if numPr is not None:
                if numPr.ilvl is not None and numPr.ilvl.val is not None:
                    ilvl = int(numPr.ilvl.val)
                if numPr.numId is not None and numPr.numId.val is not None:
                    num_id = int(numPr.numId.val)
                
                num_fmt, lvl_text = get_numbering_info(doc, num_id, ilvl)
                
            if num_fmt is not None:
                key = (num_id, ilvl)
                number_trackers[key] = number_trackers.get(key, 0) + 1
                for level in range(ilvl + 1, 9):
                    number_trackers[(num_id, level)] = 0
                    
                resolved_str = lvl_text
                for level in range(ilvl + 1):
                    level_num = number_trackers.get((num_id, level), 1)
                    lvl_num_fmt, _ = get_numbering_info(doc, num_id, level)
                    val = get_level_value(lvl_num_fmt, level_num)
                    resolved_str = resolved_str.replace(f"%{level + 1}", val)
            else:
                resolved_str = ""
            
            is_preformatted = p.style and p.style.font and p.style.font.name and 'courier' in p.style.font.name.lower()
            if not is_preformatted:
                runs_fonts = [r.font.name.lower() for r in p.runs if r.font and r.font.name]
                is_preformatted = any('courier' in f for f in runs_fonts)
                
            if is_preformatted:
                if not in_code_block:
                    in_code_block = True
                    code_lines = []
                code_lines.append(text)
                continue
            else:
                if in_code_block:
                    md_lines.append("```")
                    md_lines.extend(code_lines)
                    md_lines.append("```")
                    md_lines.append("")
                    in_code_block = False
                    
            if style_name.startswith('heading '):
                try:
                    level = int(style_name.split(' ')[1])
                except (ValueError, IndexError):
                    level = 1
                
                # Headings must be preceded by a blank line
                if md_lines and md_lines[-1] != "":
                    md_lines.append("")
                    
                header_text = text
                if num_fmt is not None and num_fmt != 'bullet':
                    header_text = f"{resolved_str} {header_text}"
                    
                md_lines.append(f"{'#' * level} {header_text}")
                md_lines.append("")
                last_item_type = 'heading'
                continue
                
            if text == "----------------------------------------------------------------------":
                if md_lines and md_lines[-1] != "":
                    md_lines.append("")
                md_lines.append("---")
                md_lines.append("")
                last_item_type = 'paragraph'
                continue
                
            # Determine if this is a bullet/unordered list
            is_bullet = False
            if numPr is not None:
                is_bullet = (num_fmt == 'bullet')
            else:
                is_bullet = 'bullet' in style_name or ('list' in style_name and 'number' not in style_name and 'ordered' not in style_name)
                
            is_list = is_bullet
            
            md_text = get_paragraph_markdown(p)
            
            if num_fmt is not None and num_fmt != 'bullet':
                if md_text.startswith('**') and md_text.endswith('**'):
                    md_text = f"**{resolved_str} {md_text[2:]}"
                else:
                    md_text = f"{resolved_str} {md_text}"
            
            if not md_text.strip():
                if md_lines and md_lines[-1] != "":
                    md_lines.append("")
                continue
                
            if is_list:
                # Lists must have a blank line before the very first list item in the block
                if last_item_type != 'list' and md_lines and md_lines[-1] != "":
                    md_lines.append("")
                    
                # Strip manual bullets typed by the user (like "+ ", "- ", "* ") if they are at the beginning
                # of the paragraph text, since python-docx treats them as literal text but Word replaced them visually.
                stripped = md_text.strip()
                if stripped.startswith('+ '):
                    md_text = md_text.replace('+ ', '', 1)
                elif stripped.startswith('- '):
                    md_text = md_text.replace('- ', '', 1)
                elif stripped.startswith('* '):
                    md_text = md_text.replace('* ', '', 1)
                    
                stripped = md_text.strip()
                if not (stripped.startswith('-') or stripped.startswith('*') or re.match(r'^\d+\.', stripped)):
                    # Compute base indentation from left_indent and first_line_indent
                    base_indent = 0
                    if p.paragraph_format:
                        if p.paragraph_format.left_indent:
                            base_indent += int(p.paragraph_format.left_indent.pt // 18)
                        if p.paragraph_format.first_line_indent and p.paragraph_format.first_line_indent.pt > 0:
                            base_indent += int(p.paragraph_format.first_line_indent.pt // 18)
                    elif ilvl > 0:
                        base_indent = ilvl
                        
                    # Capture manual tab keys
                    raw_text = p.text or ""
                    num_tabs = len(raw_text) - len(raw_text.lstrip('\t'))
                    total_indent = base_indent + num_tabs
                    
                    indent_chars = "  " * total_indent
                    clean_text = md_text.lstrip(' \t\u00a0')
                    md_lines.append(f"{indent_chars}- {clean_text}")
                else:
                    base_indent = 0
                    if p.paragraph_format:
                        if p.paragraph_format.left_indent:
                            base_indent += int(p.paragraph_format.left_indent.pt // 18)
                        if p.paragraph_format.first_line_indent and p.paragraph_format.first_line_indent.pt > 0:
                            base_indent += int(p.paragraph_format.first_line_indent.pt // 18)
                    elif ilvl > 0:
                        base_indent = ilvl
                        
                    raw_text = p.text or ""
                    num_tabs = len(raw_text) - len(raw_text.lstrip('\t'))
                    total_indent = base_indent + num_tabs
                    
                    indent_chars = "  " * total_indent
                    clean_text = md_text.lstrip(' \t\u00a0')
                    md_lines.append(f"{indent_chars}{clean_text}")
                last_item_type = 'list'
            else:
                # Normal paragraphs must be separated from preceding paragraphs, lists, or tables by a blank line
                if md_lines and md_lines[-1] != "":
                    md_lines.append("")
                
                # Apply indentation (from style left_indent, first_line_indent AND manual tab characters)
                base_indent = 0
                if p.paragraph_format:
                    if p.paragraph_format.left_indent:
                        base_indent += int(p.paragraph_format.left_indent.pt // 18)
                    if p.paragraph_format.first_line_indent and p.paragraph_format.first_line_indent.pt > 0:
                        base_indent += int(p.paragraph_format.first_line_indent.pt // 18)
                
                # Count leading tab characters in raw paragraph text
                raw_text = p.text or ""
                num_tabs = len(raw_text) - len(raw_text.lstrip('\t'))
                
                # Each tab adds one indentation level
                total_indent = base_indent + num_tabs
                
                indent_prefix = ""
                if total_indent > 0:
                    indent_prefix = "\u00a0\u00a0\u00a0\u00a0" * total_indent
                
                # Clean leading spaces/tabs from the converted markdown text to avoid duplication
                clean_text = md_text.lstrip(' \t\u00a0')
                
                md_lines.append(f"{indent_prefix}{clean_text}")
                last_item_type = 'paragraph'
                
    if in_code_block:
        md_lines.append("```")
        md_lines.extend(code_lines)
        md_lines.append("```")
        md_lines.append("")
        
    with open(output_md, 'w', encoding='utf-8') as f:
        f.write('\n'.join(md_lines))
        
    print(f"Successfully converted DOCX '{input_docx}' ➔ MD '{output_md}'")

def smart_dispatch(input_tag):
    if not input_tag or os.path.isdir(input_tag) or input_tag == '.':
        workspace = input_tag if (input_tag and os.path.isdir(input_tag)) else '.'

        # If the workspace is already inside a 'markdown' or 'docx' folder, use its parent directory
        if os.path.basename(os.path.abspath(workspace)).lower() in ['markdown', 'docx']:
            workspace = os.path.dirname(os.path.abspath(workspace))

        md_files = []
        docx_files = []
        
        for root, dirs, files in os.walk(workspace):
            dirs[:] = [d for d in dirs if not d.startswith('.') and d not in ('node_modules', 'venv', 'env', 'docx', 'markdown')]
            
            for file in files:
                ext = os.path.splitext(file)[1].lower()
                full_path = os.path.join(root, file)
                if ext == '.md':
                    md_files.append(full_path)
                elif ext == '.docx':
                    docx_files.append(full_path)
                    
        all_tags = {}
        for f in md_files:
            rel = os.path.relpath(f, workspace)
            tag = os.path.splitext(rel)[0]
            if tag not in all_tags:
                all_tags[tag] = {}
            all_tags[tag]['md'] = f
            
        for f in docx_files:
            rel = os.path.relpath(f, workspace)
            tag = os.path.splitext(rel)[0]
            if tag not in all_tags:
                all_tags[tag] = {}
            all_tags[tag]['docx'] = f
            
        docx_out_dir = os.path.join(workspace, 'docx')
        md_out_dir = os.path.join(workspace, 'markdown')
        os.makedirs(docx_out_dir, exist_ok=True)
        os.makedirs(md_out_dir, exist_ok=True)
        
        print(f"Scanning Workspace: Found {len(all_tags)} unique document tags.")
        
        for tag, files in all_tags.items():
            md_path = files.get('md')
            docx_path = files.get('docx')
            
            tag_basename = os.path.basename(tag)
            out_docx = os.path.join(docx_out_dir, tag_basename + '.docx')
            out_md = os.path.join(md_out_dir, tag_basename + '.md')
            
            if md_path and docx_path:
                md_mtime = os.path.getmtime(md_path)
                docx_mtime = os.path.getmtime(docx_path)
                
                if md_mtime >= docx_mtime:
                    print(f"\n[CONFLICT] Tag '{tag_basename}' has both formats. MD is newer.")
                    convert_md_to_docx(md_path, out_docx)
                else:
                    print(f"\n[CONFLICT] Tag '{tag_basename}' has both formats. DOCX is newer.")
                    convert_docx_to_md(docx_path, out_md)
            elif md_path:
                print(f"\n[AUTO-CONVERT] MD '{md_path}' ➔ '{out_docx}'")
                convert_md_to_docx(md_path, out_docx)
            elif docx_path:
                print(f"\n[AUTO-CONVERT] DOCX '{docx_path}' ➔ '{out_md}'")
                convert_docx_to_md(docx_path, out_md)
                
    else:
        base, ext = os.path.splitext(input_tag)
        ext = ext.lower()

        workspace = os.path.dirname(input_tag) if os.path.dirname(input_tag) else '.'

        # If the workspace is already inside a 'markdown' or 'docx' folder, use its parent directory
        if os.path.basename(os.path.abspath(workspace)).lower() in ['markdown', 'docx']:
            workspace = os.path.dirname(os.path.abspath(workspace))

        docx_out_dir = os.path.join(workspace, 'docx')
        md_out_dir = os.path.join(workspace, 'markdown')
        os.makedirs(docx_out_dir, exist_ok=True)
        os.makedirs(md_out_dir, exist_ok=True)
        
        tag_name = os.path.basename(base)
        
        if ext == '.md':
            out_docx = os.path.join(docx_out_dir, tag_name + '.docx')
            convert_md_to_docx(input_tag, out_docx)
        elif ext == '.docx':
            out_md = os.path.join(md_out_dir, tag_name + '.md')
            convert_docx_to_md(input_tag, out_md)
        else:
            md_file = input_tag + '.md'
            docx_file = input_tag + '.docx'
            
            md_exists = os.path.isfile(md_file)
            docx_exists = os.path.isfile(docx_file)
            
            out_docx = os.path.join(docx_out_dir, tag_name + '.docx')
            out_md = os.path.join(md_out_dir, tag_name + '.md')
            
            if md_exists and docx_exists:
                md_mtime = os.path.getmtime(md_file)
                docx_mtime = os.path.getmtime(docx_file)
                
                if md_mtime >= docx_mtime:
                    print(f"CONFLICT RESOLUTION: Tag '{tag_name}' has both formats. MD is newer.")
                    convert_md_to_docx(md_file, out_docx)
                else:
                    print(f"CONFLICT RESOLUTION: Tag '{tag_name}' has both formats. DOCX is newer.")
                    convert_docx_to_md(docx_file, out_md)
            elif md_exists:
                convert_md_to_docx(md_file, out_docx)
            elif docx_exists:
                convert_docx_to_md(docx_file, out_md)
            else:
                print(f"Error: Neither '{md_file}' nor '{docx_file}' was found.")
                sys.exit(1)

if __name__ == "__main__":
    input_tag = sys.argv[1] if len(sys.argv) > 1 else '.'
    smart_dispatch(input_tag)
